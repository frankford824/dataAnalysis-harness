import assert from 'node:assert/strict'
import path from 'node:path'
export async function periodCostInputScenario(page,{origin,base,artifacts}){
  const errors=[],writes=[]
  page.on('pageerror',e=>errors.push(e.message))
  page.on('console',e=>{if(e.type()==='error')errors.push(e.text())})
  page.on('request',r=>{if(r.method()==='POST'&&!r.url().includes('/_browser/')&&!r.url().includes('/telemetry/'))writes.push({url:new URL(r.url()).pathname,body:r.postDataJSON()})})
  await page.goto(base+'/#/store/s1?period=2026-06')
  assert.match(await page.title(),/记账|台账/)
  await page.getByRole('button',{name:'登录操作账号',exact:true}).click()
  await page.getByRole('textbox',{name:'操作账号名称'}).fill('browser')
  await page.getByLabel('操作账号密码',{exact:true}).fill('fixture-password-2030')
  await page.getByRole('button',{name:'登录',exact:true}).click()
  await page.getByRole('button',{name:'退出登录',exact:true}).waitFor()
  await page.getByRole('button',{name:'确认本期成本',exact:true}).click()
  const goods=page.getByRole('textbox',{name:'本期商品成本总额',exact:true})
  assert.equal(await goods.inputValue(),'','Unknown total must remain blank')
  await goods.fill('40.00')
  await page.getByRole('textbox',{name:'成本批准依据'}).fill('合成采购核定凭据，三项完整成本独立批准')
  await page.getByRole('button',{name:'预览本期成本',exact:true}).click()
  await page.getByRole('button',{name:'确认保存成本',exact:true}).waitFor()
  assert.equal(await page.getByRole('textbox',{name:/确认提成额/}).count(),0)
  assert.equal(await page.locator('vite-error-overlay').count(),0)
  await page.screenshot({path:path.join(artifacts,'period-cost-preview-desktop.png'),fullPage:false})
  const approve=page.getByRole('button',{name:'确认保存成本',exact:true})
  await approve.evaluate(node=>{node.click();node.click()})
  await approve.waitFor({state:'hidden'})
  const state=await (await page.request.get(origin+'/api/_browser/period-cost-state')).json()
  assert.equal(state.closed,false);assert.equal(state.manual_finance_count,0);assert.equal(state.payout_confirmation_count,0)
  assert.equal(state.period_cost_inputs.length,1)
  assert.equal(writes.filter(w=>w.url==='/api/automation/decisions/apply').length,1,'Double-click submits once')
  const sent=writes.find(w=>w.url==='/api/automation/decisions/preview').body
  assert.equal(sent.kind,'period_cost_input');assert.deepEqual(Object.keys(sent.values).sort(),['costs','run_id'])
  assert.deepEqual(sent.values.costs,{goods:'40.00',dropship:'0.00',reshipment:'0.00'})
  const drained=await page.request.post(origin+'/api/_browser/drain-period-cost-case')
  assert.equal(drained.status(),200,await drained.text())
  const before=(await (await page.request.get(origin+'/api/_browser/period-cost-state')).json()).period_cost_inputs
  await page.reload()
  await page.getByRole('button',{name:'撤销本期成本批准',exact:true}).click()
  await page.getByRole('textbox',{name:'成本撤销依据'}).fill('合成凭据更正，撤回整期成本批准后重新补证')
  await page.getByRole('button',{name:'预览撤销成本批准',exact:true}).click()
  await page.getByRole('button',{name:'确认撤销成本批准',exact:true}).waitFor()
  await page.setViewportSize({width:390,height:844})
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'Mobile approval stays within viewport')
  await page.screenshot({path:path.join(artifacts,'period-cost-revoke-mobile.png'),fullPage:false})
  await page.getByRole('button',{name:'确认撤销成本批准',exact:true}).click()
  await page.getByRole('button',{name:'确认撤销成本批准',exact:true}).waitFor({state:'hidden'})
  const revoked=await page.request.post(origin+'/api/_browser/drain-period-cost-case')
  assert.equal(revoked.status(),200,await revoked.text())
  const after=await (await page.request.get(origin+'/api/_browser/period-cost-state')).json()
  assert.equal(after.closed,false);assert.equal(after.manual_finance_count,0);assert.equal(after.payout_confirmation_count,0)
  assert.deepEqual(after.period_cost_inputs,before,'Revocation appends a decision without rewriting approved cost facts')
  assert.equal(after.revocations,1)
  assert.equal(writes.some(w=>/\/close$|close-batches\/confirm|payout/.test(w.url)),false)
  assert.deepEqual(errors,[])
  return 'actual HTTP costs approved and revoked while open; no payout/close writes; exact preview and double-click protection; desktop/mobile'
}
