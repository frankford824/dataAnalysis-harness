import assert from 'node:assert/strict'
async function settledModal(page){
  await page.evaluate(async()=>Promise.all(document.getAnimations().filter(a=>Number.isFinite(a.effect?.getTiming().iterations)).map(a=>a.finished.catch(()=>{}))))
  await page.waitForFunction(()=>{const node=document.querySelector('.n-modal');if(!node)return false;const box=node.getBoundingClientRect();return box.left>=-2&&box.right<=innerWidth+2&&box.top>=-2&&box.bottom<=innerHeight+2})
}
export async function closeRefreshScenario(page,artifacts){
  await page.getByRole('heading',{name:'月度工作台',exact:true}).waitFor()
  await page.getByRole('tab',{name:/需你决定/}).click()
  await page.getByRole('button',{name:'预览本月全公司结账',exact:true}).click()
  const progress=page.getByLabel('结账前自动复核进度',{exact:true})
  await progress.getByText('正在重新核查上游来源',{exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'确认本次结账',exact:true}).count(),0)
  assert.equal(await page.evaluate(()=>window.closeRefreshRegression.confirmations.length),0)
  const first=await page.evaluate(()=>window.closeRefreshRegression.previews[0])
  await page.keyboard.press('Escape')
  await progress.waitFor({state:'hidden'})
  await page.getByRole('button',{name:'预览月结',exact:true}).click()
  await progress.getByText('正在重新核查上游来源',{exact:true}).waitFor()
  assert.deepEqual(await page.evaluate(()=>window.closeRefreshRegression.previews[1]),first,
    'Reopening from the decision card must resume the same in-flight capture')
  await settledModal(page)
  if(artifacts)await page.screenshot({path:artifacts+'/close-source-refresh-desktop.png',fullPage:false})
  await page.setViewportSize({width:390,height:844})
  await settledModal(page)
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2))
  if(artifacts)await page.screenshot({path:artifacts+'/close-source-refresh-mobile.png',fullPage:false})
  await page.evaluate(()=>{window.closeRefreshRegression.phase='quote'})
  await progress.getByRole('button',{name:'继续检查本批',exact:true}).click()
  await progress.getByText('原日报价 0 / 1',{exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'确认本次结账',exact:true}).count(),0)
  await page.evaluate(()=>{window.closeRefreshRegression.phase='pending'})
  await progress.getByRole('button',{name:'继续检查本批',exact:true}).click()
  await progress.getByRole('heading',{name:'本批依据待核',exact:true}).waitFor()
  assert.equal(await page.getByRole('button',{name:'确认本次结账',exact:true}).count(),0)
  await page.evaluate(()=>{window.closeRefreshRegression.phase='source'})
  await progress.getByRole('button',{name:'重新检查已恢复的来源',exact:true}).click()
  await progress.getByText('正在重新核查上游来源',{exact:true}).waitFor()
  await page.evaluate(()=>{window.closeRefreshRegression.phase='quote'})
  await progress.getByRole('button',{name:'继续检查本批',exact:true}).click()
  await progress.getByText('原日报价 0 / 1',{exact:true}).waitFor()
  await page.evaluate(()=>{window.closeRefreshRegression.phase='ready'})
  await progress.getByRole('button',{name:'继续检查本批',exact:true}).click()
  await page.getByText('本次可确认 1 家；0 家继续保留，原已结账结果不变。',{exact:true}).waitFor()
  const calls=await page.evaluate(()=>window.closeRefreshRegression.previews)
  assert.equal(calls.length,7);for(const call of calls.slice(0,4))assert.deepEqual(call,first)
  assert.notEqual(calls[4].request_id,first.request_id)
  assert.deepEqual(calls[4].store_ids,first.store_ids,'Explicit recapture must preserve this batch scope')
  for(const call of calls.slice(4))assert.deepEqual(call,calls[4])
  await page.getByRole('button',{name:'确认本次结账',exact:true}).click()
  await page.waitForFunction(()=>window.closeRefreshRegression.confirmations.length===1)
  assert.equal(await page.getByRole('textbox',{name:'兼职费用总额'}).count(),0)
  return 'durable source -> quote -> proposal uses one request; no premature close or repeated amount entry'
}
