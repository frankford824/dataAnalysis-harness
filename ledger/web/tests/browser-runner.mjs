function start(command,args,env={}){
  const child=spawn(command,args,{cwd:repo,env:{...process.env,...env},stdio:['ignore','pipe','pipe'],detached:process.platform!=='win32'})
  children.push(child)
  child.stdout.on('data',chunk=>logs.push(String(chunk)));child.stderr.on('data',chunk=>logs.push(String(chunk)))
  child.on('error',error=>logs.push(error.stack))
  return child
}
async function ready(url,child){
  const deadline=Date.now()+30000
  while(Date.now()<deadline){
    if(child.exitCode!==null)throw Error(`Server exited ${child.exitCode}: ${logs.join('').slice(-3000)}`)
    try{if((await fetch(url,{signal:AbortSignal.timeout(1000)})).ok)return}catch{}
    await new Promise(resolve=>setTimeout(resolve,150))
  }
  throw Error(`Server not ready: ${url}`)
}
async function pollJson(request,url,predicate,timeout=15000){
  const deadline=Date.now()+timeout
  while(Date.now()<deadline){
    const response=await request.get(url,{timeout:3000})
    assert.equal(response.status(),200,`Polling failed: ${url}`)
    const result=predicate(await response.json())
    assert.equal(typeof result,'boolean','Polling predicates must return a boolean')
    if(result)return
    await new Promise(resolve=>setTimeout(resolve,100))
  }
  throw Error(`Expected HTTP condition did not become true: ${url}`)
}
async function stop(child){
  if(child.exitCode!==null)return
  try{if(process.platform==='win32')child.kill();else process.kill(-child.pid,'SIGTERM')}catch{}
  await Promise.race([new Promise(resolve=>child.once('exit',resolve)),new Promise(resolve=>setTimeout(resolve,2000))])
  if(child.exitCode===null){try{if(process.platform==='win32')child.kill('SIGKILL');else process.kill(-child.pid,'SIGKILL')}catch{}}
}
